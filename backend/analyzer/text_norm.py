"""
text_norm.py
============================================================================
  >>> ทำข้อความในหน้าเว็บให้เป็นมาตรฐานก่อนเอาไปเทียบชื่อแบรนด์ <<<
============================================================================
ปัญหาที่โมดูลนี้แก้: กฎ "หน้าเว็บอ้างถึงแบรนด์" ที่เทียบข้อความตรง ๆ เลี่ยงได้ง่ายมาก
คนเขียนหน้าฟิชชิ่งแค่พิมพ์ชื่อแบรนด์ให้เพี้ยนนิดเดียวก็รอดแล้ว โดยที่คนอ่านยัง
เห็นเป็นคำเดิมทุกประการ เพราะเบราว์เซอร์เป็นคนแปลงกลับให้ตอนแสดงผล:

    &#103;oogle          -> เบราว์เซอร์แสดง "google"   (HTML entity)
    ｇｏｏｇｌｅ          -> ตาคนอ่านว่า "google"        (อักษรเต็มความกว้าง)
    goo<U+200B>gle     -> ตาคนอ่านว่า "google"        (อักขระความกว้างศูนย์)
    g00gle             -> ตาคนอ่านว่า "google"        (ตัวเลขแทนตัวอักษร)

ลำดับการล้างสำคัญ ต้องคลาย entity ก่อนเสมอ ไม่งั้น NFKC จะไม่เห็นตัวอักษรจริงที่
ซ่อนอยู่ในรูป &#xxx; และต้องลบอักขระความกว้างศูนย์หลัง NFKC เพราะ NFKC ไม่ลบให้

**หลักการใช้งาน: ต้องเทียบสองรอบเสมอ** — ทั้งข้อความดิบและข้อความที่ล้างแล้ว
ถ้าเจอชื่อแบรนด์เฉพาะในรอบหลัง แปลว่าหน้านั้น "จงใจอำพราง" ซึ่งน่าสงสัยกว่าการ
เขียนชื่อแบรนด์ตรง ๆ มาก (เว็บจริงไม่มีเหตุผลอะไรที่จะเขียนชื่อตัวเองแบบเข้ารหัส)
ดู brand_hidden_in_text ใน content_analyzer.py

โมดูลนี้เป็น pure function ล้วน ไม่แตะเครือข่ายและไม่ import Flask — เทสต์ได้ตรง ๆ
"""
import html
import re
import unicodedata

from .heuristics import normalize_glyphs

# อักขระที่มองไม่เห็นแต่แทรกกลางคำได้ ทำให้การเทียบสตริงพลาด
#   200b ZERO WIDTH SPACE      200c ZERO WIDTH NON-JOINER
#   200d ZERO WIDTH JOINER     2060 WORD JOINER
#   feff ZERO WIDTH NO-BREAK SPACE (BOM)
#   00ad SOFT HYPHEN           034f COMBINING GRAPHEME JOINER
#   200e/200f, 202a-202e, 2066-2069 = ตัวคุมทิศทางข้อความ (ใช้สลับลำดับที่ตาเห็นได้)
# ระบุเป็นเลขรหัสโดยตั้งใจ ถ้าวางตัวอักษรจริงลงไปในโค้ดจะมองไม่เห็นและแก้ผิดได้ง่าย
_INVISIBLE_CODEPOINTS = (
    0x200B, 0x200C, 0x200D, 0x2060, 0xFEFF, 0x00AD, 0x034F,
    0x200E, 0x200F, 0x202A, 0x202B, 0x202C, 0x202D, 0x202E,
    0x2066, 0x2067, 0x2068, 0x2069,
)
_INVISIBLE = re.compile("[" + "".join(chr(c) for c in _INVISIBLE_CODEPOINTS) + "]")

_WHITESPACE = re.compile(r"\s+")


def strip_invisible(s: str) -> str:
    """ลบอักขระที่มองไม่เห็นทั้งหมดออก (แทรกกลางคำเพื่อเลี่ยงการเทียบสตริง)"""
    return _INVISIBLE.sub("", s)


def normalize_text(s: str) -> str:
    """ล้างข้อความให้เหลือรูปที่ "ตาคนอ่านออก" แล้วเทียบได้จริง

    ทำ 5 อย่างตามลำดับนี้เท่านั้น:
      1) คลาย HTML entity สองรอบ (`&amp;#103;` ซ้อนชั้นเป็นเทคนิคที่พบจริง)
      2) normalize Unicode แบบ NFKC (ｇ -> g, ﬁ -> fi)
      3) ลบอักขระความกว้างศูนย์/ตัวคุมทิศทาง
      4) normalize_glyphs() ที่ใช้อยู่แล้วในชั้นที่ 2 (g00gle -> google, rn -> m)
      5) ยุบช่องว่างซ้ำและตัดหัวท้าย
    """
    if not s:
        return ""
    s = html.unescape(html.unescape(s))
    s = unicodedata.normalize("NFKC", s)
    s = strip_invisible(s)
    s = normalize_glyphs(s)
    return _WHITESPACE.sub(" ", s).strip()


def flatten(s: str) -> str:
    """รูปแบบที่หลวมที่สุด: เอาทุกอย่างที่ไม่ใช่ตัวอักษร/ตัวเลขออก

    ใช้จับการแทรกตัวคั่นกลางชื่อแบรนด์ (`g-o-o-g-l-e`, `g.o.o.g.l.e`) ซึ่ง
    normalize_text() จับไม่ได้เพราะขีดกับจุดเป็นอักขระที่ถูกต้องตามปกติ
    **ห้ามใช้ตัวนี้เป็นหลักฐานเดี่ยว ๆ** เพราะการลบตัวคั่นทิ้งทำให้คำที่ไม่เกี่ยวกัน
    มาต่อกันเป็นชื่อแบรนด์ได้ง่าย (false positive) — ใช้เป็นตัวประกอบเท่านั้น
    """
    return re.sub(r"[^a-z0-9฀-๿]", "", normalize_text(s).lower())


def contains_word(text: str, word: str) -> bool:
    """หา `word` ในข้อความแบบมีขอบเขตคำ (กัน "line" ไปโดนคำว่า "online")

    ใช้ขอบเขตแบบ "ไม่ใช่ตัวอักษรละติน" แทน \\b ของ regex เพราะข้อความไทยไม่มี
    ช่องว่างคั่นคำ — `\\b` จะให้ผลผิดเมื่อชื่อแบรนด์ติดกับอักษรไทย
    """
    if not text or not word:
        return False
    pattern = r"(^|[^a-z0-9])" + re.escape(word.lower()) + r"([^a-z0-9]|$)"
    return bool(re.search(pattern, text.lower()))
