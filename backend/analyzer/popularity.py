"""
popularity.py
============================================================================
  >>> "โดเมนนี้มีคนใช้จริงมากแค่ไหน" — เทียบกับรายการอันดับที่เก็บไว้ในเครื่อง <<<
============================================================================
เว็บที่คนทั้งโลกเข้าทุกวันเป็นล้านครั้งไม่ใช่เว็บที่มิจฉาชีพเพิ่งจดเมื่อวาน ความนิยม
จึงเป็น "หลักฐานฝั่งปลอดภัย" ที่หาได้จากตัวโดเมนล้วน ๆ ไม่ต้องดูเนื้อหาหน้าเว็บเลย

ทำไมต้องเป็นไฟล์ในเครื่อง ไม่ใช่ยิง API ถามใคร:
  1) **เว็บที่ถูกตรวจไม่มีทางรู้ตัว** — การเทียบทั้งหมดเกิดในหน่วยความจำของเราเอง
     ไม่มีแพ็กเก็ตวิ่งออกไปหาโดเมนนั้นหรือหาบริการภายนอกใด ๆ ต่างจากการดึงหน้าเว็บ
     (ชั้น 4) ที่เจ้าของเว็บเห็น log ได้ว่ามีใครมาส่อง
  2) เร็วระดับ dict lookup จึงใส่ไว้ในชั้น 2 (ออฟไลน์) ได้โดยไม่ทำให้การตรวจช้าลง
     และผู้ใช้ที่ไม่ได้ล็อกอิน (ซึ่งได้แค่ชั้น 1-2) ก็ได้ประโยชน์ด้วย
  3) เทสต์ได้โดยไม่ต้องมีเน็ต ตามกติกาของโฟลเดอร์ analyzer/ ทั้งโฟลเดอร์

**ไม่มีไฟล์รายการ = ฟีเจอร์นี้เงียบไปเฉย ๆ** (rank() คืน None ทุกครั้ง) ระบบส่วนอื่น
ทำงานปกติทุกประการ — หลักการเดียวกับ SANDBOX_URL ที่ไม่ตั้งค่าก็ยังใช้งานได้

ข้อควรระวังที่สำคัญที่สุด (อ่านก่อนเอาไปใช้ต่อ):
  **"อันดับสูง" ไม่ได้แปลว่า "ปลอดภัย"** โดยเฉพาะโดเมนของบริการที่ให้คนอื่นเอาเว็บ
  มาฝาก — ตอนวัดกับ testset_100.json พบว่าลิงก์ฟิชชิ่งที่ยังทำงานอยู่จริง 22 จาก 50
  ลิงก์ อยู่ในรายการนี้ทั้งหมด และ *ทุกอันเป็นโดเมนของแพลตฟอร์มฝากเว็บ* เช่น
  amazonaws.com (อันดับ 7!), github.io (121), pages.dev (214), vercel.app (670)
  คนที่ฝากเว็บฟิชชิ่งไว้ได้อันดับของแพลตฟอร์มไปฟรี ๆ
  ผู้เรียกใช้จึงต้องกรอง USER_CONTENT_DOMAINS/SHORTENERS ออกก่อนเสมอ
  (heuristics._trust_signals ทำให้แล้ว — อย่าเรียก rank() ตรง ๆ เพื่อตัดสินใจเอง)

รูปแบบไฟล์: โดเมนบรรทัดละหนึ่งอัน เรียงตามอันดับจากนิยมที่สุดลงมา
บรรทัดว่างและบรรทัดที่ขึ้นต้นด้วย # ถูกข้าม (ใช้เขียนหัวไฟล์บอกที่มา/วันที่ดึง)
สร้าง/อัปเดตไฟล์ด้วย backend/tools/update_popularity.py
"""
import os
import threading

# ไฟล์รายการอันดับ — ตั้ง POPULARITY_LIST ทับได้ (เช่นชี้ไปไฟล์เล็ก ๆ ตอนเทสต์)
DEFAULT_LIST_PATH = os.path.join(os.path.dirname(__file__), "data", "popular_domains.txt")

_lock = threading.Lock()
_ranks = None      # dict[str, int] | None  (None = ยังไม่ได้พยายามโหลด)
_loaded_from = ""  # path ที่โหลดได้จริง ("" = ไม่มีไฟล์)


def _list_path() -> str:
    return os.environ.get("POPULARITY_LIST") or DEFAULT_LIST_PATH


def _load_locked():
    """อ่านไฟล์เข้า dict — ต้องถือ _lock อยู่แล้วตอนเรียก"""
    global _ranks, _loaded_from
    path = _list_path()
    ranks = {}
    try:
        with open(path, encoding="utf-8") as fh:
            n = 0
            for line in fh:
                d = line.strip().lower()
                if not d or d.startswith("#"):
                    continue
                n += 1
                # เจอโดเมนซ้ำให้ยึดอันดับแรก (ดีที่สุด) ที่เจอ
                if d not in ranks:
                    ranks[d] = n
        _loaded_from = path
    except OSError:
        # ไม่มีไฟล์/อ่านไม่ได้ = ปิดฟีเจอร์เงียบ ๆ ไม่ทำให้การตรวจลิงก์ล้ม
        _loaded_from = ""
    _ranks = ranks


def _ensure_loaded():
    global _ranks
    if _ranks is None:
        with _lock:
            if _ranks is None:      # เช็กซ้ำหลังได้ lock (กันสองเธรดโหลดพร้อมกัน)
                _load_locked()


def reset():
    """ทิ้งข้อมูลที่โหลดไว้ ให้ครั้งต่อไปอ่านไฟล์ใหม่
    (ใช้ตอนเทสต์ที่สลับ POPULARITY_LIST ไปมา — โค้ดจริงไม่ต้องเรียก)"""
    global _ranks, _loaded_from
    with _lock:
        _ranks = None
        _loaded_from = ""


def rank(domain: str):
    """คืนอันดับความนิยมของโดเมน (1 = นิยมที่สุด) หรือ None ถ้าไม่อยู่ในรายการ
    หรือยังไม่ได้ติดตั้งไฟล์รายการไว้

    รับ "โดเมนจริง" (registrable / eTLD+1) เป็นหลัก เพราะรายการอันดับก็เก็บระดับนั้น
    — ส่ง www.example.com เข้ามาจะหาไม่เจอ ผู้เรียกต้องตัด subdomain มาก่อน"""
    if not domain:
        return None
    _ensure_loaded()
    return _ranks.get(domain.lower())


def status() -> dict:
    """สถานะของรายการอันดับ สำหรับหน้าเช็กสุขภาพระบบ/ตอนไล่ปัญหา
    (โหลดไฟล์ให้ด้วยถ้ายังไม่ได้โหลด จะได้รู้ว่าไฟล์ใช้ได้จริงไหม)"""
    _ensure_loaded()
    return {"available": bool(_ranks), "entries": len(_ranks or {}),
            "path": _loaded_from or _list_path(), "loaded": bool(_loaded_from)}
