# -*- coding: utf-8 -*-
"""
combos.py
============================================================================
  >>> กฎการรวมสัญญาณ: สัญญาณอ่อนหลายอันที่ "อยู่ด้วยกันแล้วน่ากลัว" <<<
============================================================================
ระบบเดิมบวกคะแนนของแต่ละสัญญาณตรง ๆ ซึ่งถูกต้องในกรณีทั่วไป แต่มีจุดบอดหนึ่งจุด:
สัญญาณบางคู่มีความหมายมากกว่าผลบวกของมันเอง

    หน้าที่ "อ้างชื่อธนาคาร"        อย่างเดียว -> อาจเป็นข่าว/บล็อกรีวิว
    หน้าที่ "มีช่องรหัสผ่าน"        อย่างเดียว -> เว็บล็อกอินปกติทุกเว็บก็มี
    ทั้งสองอย่างพร้อมกัน                      -> หน้าหลอกขโมยบัญชีแทบจะแน่นอน

โมดูลนี้จึงเพิ่ม "คะแนนพิเศษ" ให้เฉพาะตอนที่สัญญาณมาพร้อมกันครบชุด ตามตาราง
COMBO_RULES ใน config.py (Analyst แก้ตารางนั้นได้โดยไม่ต้องแตะโค้ดนี้)

กติกาที่ห้ามผิด — **นับเฉพาะสิ่งที่ตรวจแล้วว่าเจอจริงเท่านั้น**
ถ้าชั้นไหนเช็กไม่ได้ (เช่น ดึงหน้าเว็บไม่มา หรือ RDAP ไม่ตอบ) สัญญาณของชั้นนั้นจะ
ไม่อยู่ในเซ็ตที่ส่งเข้ามาตั้งแต่แรก combo จึงไม่มีทางถูกจุดจากการ "เดา" ได้
— หลักการเดียวกับที่ระบบไม่นับ "เช็กไม่ได้" เป็น "เสี่ยง"

เป็น pure function ล้วน: เซ็ตเข้า รายการสัญญาณออก เทสต์ได้โดยไม่ต้องมีเน็ต
"""
from .config import COMBO_RULES


def apply_combos(present: set) -> list:
    """รับเซ็ตของ "สิ่งที่ยืนยันแล้วว่าพบ" (id ของสัญญาณ + ข้อเท็จจริง เช่น
    has_password_input) คืนรายการสัญญาณโบนัสของ combo ที่เข้าเงื่อนไขครบ

    severity เป็น "high" ไม่ใช่ "critical" โดยตั้งใจ — critical ทำให้ระบบฟันธงแดง
    ทันทีโดยไม่ดูคะแนน ซึ่งแรงเกินไปสำหรับกฎที่สร้างจากสัญญาณอ่อนหลายตัวมารวมกัน
    ปล่อยให้ผลรวมคะแนนเป็นตัวตัดสินตามปกติจะตรวจสอบย้อนกลับได้ง่ายกว่า
    """
    if not present:
        return []

    hits = []
    for rule in COMBO_RULES:
        if rule["needs"] <= present:
            hits.append({
                "id": rule["id"],
                "title": rule["title"],
                "detail": rule["detail"],
                "points": rule["bonus"],
                "severity": "high",
                "combo_of": sorted(rule["needs"]),
            })
    return hits
